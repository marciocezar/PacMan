/**
 * Bitmaps de 8×8 lidos da ROM (página $FD).
 * O kernel desenha de baixo para cima: o último byte é o topo na tela.
 * $FD8B, $FD93, $FD9B e $FDA3 são o corpo do fantasma (saia alternada).
 * $FDC6 é o par de olhos que sobra depois que o fantasma é comido.
 */

export const GHOST_FRAMES: readonly (readonly number[])[] = [
  [0xaa, 0xff, 0xff, 0xff, 0x99, 0xdd, 0x7e, 0x3c],
  [0x55, 0xff, 0xff, 0xff, 0x99, 0xbb, 0x7e, 0x3c],
  [0xaa, 0xff, 0xff, 0xff, 0xbb, 0x99, 0x7e, 0x3c],
  [0x55, 0xff, 0xff, 0xff, 0xdd, 0x99, 0x7e, 0x3c],
];

export const EYES_ONLY: readonly number[] = [0x00, 0xe7, 0xa5, 0xe7, 0x00, 0x00, 0x00, 0x00];

/** Círculo de 8×8 usado para o Pac-Man. A boca é apagada na hora de desenhar. */
export const PAC_DISC: readonly number[] = [
  0x3c, 0x7e, 0xff, 0xff, 0xff, 0xff, 0x7e, 0x3c,
];

export function bitOn(rowByte: number, column: number): boolean {
  return (rowByte & (0x80 >> column)) !== 0;
}
